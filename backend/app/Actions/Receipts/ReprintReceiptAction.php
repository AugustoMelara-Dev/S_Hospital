<?php

namespace App\Actions\Receipts;

use App\Actions\Billing\PreservesIssuedTimestamps;
use App\Models\Invoice;
use App\Models\User;
use App\Support\AuditLogger;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * Legacy invoice-receipt reprint path (GET/POST JSON receipt preview).
 *
 * HS-PRINT-DELIVERY boundaries for this path:
 * - Issuing the invoice is not printing. The first authorized print is the
 *   `GET /api/invoices/{invoice}/receipt` view returning copy_label "Original";
 *   viewing/printing that document does not mutate the counter.
 * - This action only runs for the explicit reprint request. It increments the
 *   durable `invoices.legacy_reprint_count` inside the transaction (row lock)
 *   and labels the document `REIMPRESIÓN #n` with n = counter after the
 *   increment (first reprint = #1), returning the financial snapshot unchanged.
 * - A human reason of 5-500 characters is mandatory and is never substituted by a
 *   canned string generated by the backend or the frontend (see ReprintReason).
 * - The reprint number is NOT derived from COUNT(audit_logs): audit_logs is the
 *   append-only trail (and is prunable), not a durable counter. The number comes
 *   from `invoices.legacy_reprint_count` and survives audit pruning, reloads and
 *   new sessions; it is the legacy analogue of the institutional receipt's
 *   `reprint_count` + print events.
 *
 * @see ReprintReason
 */
class ReprintReceiptAction
{
    // M-W2-RCP-04: el UPDATE de la factura (legacy_reprint_count) no debe dejar
    // que MariaDB reescriba `invoices.issued_at` (hecho fiscal historico).
    use PreservesIssuedTimestamps;

    public function __construct(
        private readonly GenerateReceiptDataAction $generateReceiptData,
        private readonly AuditLogger $auditLogger,
    ) {}

    /** @return array{receipt: array<string, mixed>, audit: array<string, mixed>} */
    public function execute(Invoice $invoice, User $user, string $width, ?string $reason = null, ?Request $request = null): array
    {
        // Defense in depth: the Form Request already validates the payload, but the
        // action is the last barrier for every internal caller and must not accept a
        // missing/blank/automatic reason.
        $humanReason = ReprintReason::assertValid($reason);

        return DB::transaction(function () use ($invoice, $user, $width, $humanReason, $request) {
            $lockedInvoice = Invoice::query()
                ->whereKey($invoice->id)
                ->lockForUpdate()
                ->firstOrFail();

            if ($lockedInvoice->status === Invoice::STATUS_VOID) {
                throw ValidationException::withMessages([
                    'invoice' => 'No se puede reimprimir una factura anulada.',
                ]);
            }

            // M-W2-RCP-04: capturar issued_at ANTES de tocar la fila. Con
            // explicit_defaults_for_timestamp=0 MariaDB reescribe la columna
            // TIMESTAMP implicita (issued_at) en cualquier UPDATE que no la
            // asigne; la reimpresion no es un hecho fiscal nuevo.
            $issuedAt = $lockedInvoice->issued_at;

            // Contador durable del path legacy: incremento y numero visible se
            // resuelven dentro de la misma transaccion y bajo el lock de la fila
            // (SELECT ... FOR UPDATE). No depende de audit_logs, que es podable.
            $reprintNumber = ((int) $lockedInvoice->legacy_reprint_count) + 1;
            $lockedInvoice->forceFill([
                'legacy_reprint_count' => $reprintNumber,
            ])->save();

            // Restaura el valor original reasignandolo explicitamente (una
            // columna asignada de forma explicita no dispara el auto-update).
            $this->preserveInvoiceIssuedAt($lockedInvoice, $issuedAt);

            $copyLabel = 'REIMPRESIÓN #'.$reprintNumber;

            $receipt = $this->generateReceiptData->execute($lockedInvoice, $width, $copyLabel);

            $this->auditLogger->log(
                action: 'invoice.reprinted',
                entity: $lockedInvoice,
                user: $user,
                request: $request,
                newValues: [
                    'invoice_number' => $lockedInvoice->invoice_number,
                    'width' => $width,
                    'reason' => $humanReason,
                    'copy_label' => $copyLabel,
                    'legacy_reprint_count' => $reprintNumber,
                ],
                reason: $humanReason,
            );

            return [
                'receipt' => $receipt,
                'audit' => [
                    'action' => 'invoice.reprinted',
                    'invoice_id' => $lockedInvoice->id,
                    'width' => $width,
                    'reason' => $humanReason,
                    'copy_label' => $copyLabel,
                    'legacy_reprint_count' => $reprintNumber,
                ],
            ];
        });
    }
}
